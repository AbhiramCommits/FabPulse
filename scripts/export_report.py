#!/usr/bin/env python3
"""Export the FabPulse engineer summary as Markdown, CSV or JSON.

The report payload comes from :func:`fabpulse.report.build_summary`, so the
browser page, this CLI and any downstream consumer read exactly the same
numbers.

Usage:
    python scripts/export_report.py --format md --out reports/
    python scripts/export_report.py --format csv --out reports/ --tool-family SCANNER
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "api"))

from fabpulse import report  # noqa: E402  (path setup must come first)
from fabpulse.filters import Filters  # noqa: E402


def _md(value: Any) -> str:
    """Escape pipe characters so values survive Markdown tables."""
    return str(value if value is not None else "n/a").replace("|", "\\|")


def render_markdown(data: dict[str, Any]) -> str:
    """Render the structured summary as a standalone Markdown document."""
    filters = data["filters"]
    scope = (
        f"{data['date_range']['min_date']} → {data['date_range']['max_date']}"
        if data["date_range"].get("min_date")
        else "all available data"
    )
    lines: list[str] = [
        "# FabPulse engineer report",
        "",
        f"Generated: {data['generated_at']}  ",
        f"Window: {scope}  ",
        f"Tools: {data['counts'].get('tools', 0)} · "
        f"Events: {int(data['counts'].get('events', 0)):,} · "
        f"Faults: {int(data['counts'].get('fault_events', 0)):,}",
        "",
        "## Headline KPIs",
        "",
        "| Metric | Value | What it means |",
        "| --- | --- | --- |",
    ]
    for item in data["headline"]:
        lines.append(f"| {_md(item['label'])} | **{_md(item['value'])}** | {_md(item['detail'])} |")

    lines.extend(["", "## What the data says", ""])
    for sentence in data["summary_sentences"]:
        lines.append(f"- {sentence}")

    lines.extend(
        [
            "",
            "## Top ranked excursions",
            "",
            "| # | Tool | Metric | Severity | Finding |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    if data["excursions"]:
        for item in data["excursions"]:
            lines.append(
                f"| {item['rank']} | {_md(item['tool_id'])} | {_md(item['metric'])} | "
                f"{_md(item['severity'])} | {_md(item['headline'])} |"
            )
    else:
        lines.append("| — | — | — | — | No excursions in this window. |")

    lines.extend(
        [
            "",
            "## Pareto: fault codes behind 80% of events",
            "",
            "| Fault code | Category | Severity | Events | % of total | Cumulative % |",
            "| --- | --- | --- | ---: | ---: | ---: |",
        ]
    )
    for row in data["pareto_drivers"]:
        lines.append(
            f"| {_md(row['fault_code'])} | {_md(row['fault_category'])} | "
            f"{_md(row['severity'])} | {row['count']:,} | {row['pct_of_total']:.1f}% | "
            f"{row['cumulative_pct']:.1f}% |"
        )

    lines.extend(
        [
            "",
            "## Most significant shift-over-shift deltas",
            "",
            "| Tool | Handoff | Δ | Δ % | Welch p | Significant |",
            "| --- | --- | ---: | ---: | --- | --- |",
        ]
    )
    for item in data["shift_deltas"]:
        p_value = item.get("p_value")
        p_text = "n/a" if p_value is None else ("< 0.001" if p_value < 0.001 else f"{p_value:.3f}")
        pct = item.get("pct_delta")
        lines.append(
            f"| {_md(item['tool_id'])} | {item['from_shift']} → {item['to_shift']} | "
            f"{item['abs_delta']:+.2f} | {pct:+.1f}% | {p_text} | "
            f"{'yes' if item.get('significant') else 'no'} |"
        )

    lines.extend(["", "## Glossary", ""])
    for entry in data["glossary"]:
        lines.append(f"- **{entry['term']}** — {entry['definition']}")

    lines.extend(
        [
            "",
            "---",
            "",
            f"Filters: `{json.dumps(filters, sort_keys=True)}`",
            "",
            "Generated by FabPulse. Control limits use mean ± 3σ; Tukey fences use 1.5×IQR.",
        ]
    )
    return "\n".join(lines) + "\n"


def render_csv(data: dict[str, Any]) -> str:
    """Render a tidy, machine-readable CSV with one row per report item."""
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["section", "item", "detail", "value"])
    for item in data["headline"]:
        writer.writerow(["headline", item["label"], item["detail"], item["value"]])
    for sentence in data["summary_sentences"]:
        writer.writerow(["summary", "finding", sentence, ""])
    for item in data["excursions"]:
        writer.writerow(
            [
                "excursion",
                f"#{item['rank']} {item['tool_id']} {item['metric']}",
                item["headline"],
                item["severity"],
            ]
        )
    for row in data["pareto_drivers"]:
        writer.writerow(
            [
                "pareto",
                row["fault_code"],
                f"{row['fault_category']} / {row['severity']}",
                f"{row['count']} events ({row['pct_of_total']:.1f}%, cumulative {row['cumulative_pct']:.1f}%)",
            ]
        )
    for item in data["shift_deltas"]:
        p_value = item.get("p_value")
        writer.writerow(
            [
                "shift_delta",
                f"{item['tool_id']} {item['from_shift']}->{item['to_shift']}",
                f"p={p_value}" if p_value is not None else "p=n/a",
                f"{item['pct_delta']:+.1f}%" if item.get("pct_delta") is not None else "",
            ]
        )
    for entry in data["glossary"]:
        writer.writerow(["glossary", entry["term"], entry["definition"], ""])
    return buffer.getvalue()


def write_report(data: dict[str, Any], fmt: str, out_dir: str | Path) -> Path:
    """Write the rendered report and return its path.

    Args:
        data: Payload from :func:`fabpulse.report.build_summary`.
        fmt: One of ``md``, ``csv`` or ``json``.
        out_dir: Destination directory (created if missing).
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    if fmt == "md":
        content = render_markdown(data)
        path = out / "fabpulse_report.md"
    elif fmt == "csv":
        content = render_csv(data)
        path = out / "fabpulse_report.csv"
    elif fmt == "json":
        content = json.dumps(data, indent=2) + "\n"
        path = out / "fabpulse_report.json"
    else:
        raise ValueError(f"unsupported format: {fmt}")
    path.write_text(content, encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    """CLI entry point for the report exporter."""
    parser = argparse.ArgumentParser(description="Export the FabPulse engineer report")
    parser.add_argument("--format", choices=("md", "csv", "json"), default="md")
    parser.add_argument("--out", default="reports", help="output directory")
    parser.add_argument("--from-date", type=date.fromisoformat, default=None)
    parser.add_argument("--to-date", type=date.fromisoformat, default=None)
    parser.add_argument("--tool-family", default=None)
    parser.add_argument("--fab-site", default=None)
    parser.add_argument("--tool-ids", default="", help="comma-separated tool ids")
    parser.add_argument("--shifts", default="", help="comma-separated shift codes")
    parser.add_argument("--metric", default="throughput_wph")
    args = parser.parse_args(argv)

    filters = Filters.from_mapping(
        {
            "from_date": args.from_date,
            "to_date": args.to_date,
            "tool_family": args.tool_family,
            "fab_site": args.fab_site,
            "tool_ids": args.tool_ids,
            "shifts": args.shifts,
        }
    )
    try:
        filters.validate()
        data = report.build_summary(filters, metric=args.metric)
        path = write_report(data, args.format, args.out)
    except ValueError as exc:
        print(f"export failed: {exc}", file=sys.stderr)
        return 1

    size_kb = path.stat().st_size / 1024
    print(f"wrote {path} ({size_kb:.1f} KB)")
    if data["summary_sentences"]:
        print(f"headline: {data['summary_sentences'][0]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

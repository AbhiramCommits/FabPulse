import type { ReportResponse } from '../api/types'

function escapeCsv(value: string): string {
  if (/[",\n]/.test(value)) return `"${value.replace(/"/g, '""')}"`
  return value
}

function md(value: string | number | null | undefined): string {
  return String(value ?? 'n/a').replace(/\|/g, '\\|')
}

/** Render the same structured report as the backend Markdown exporter. */
export function reportToMarkdown(data: ReportResponse): string {
  const bounds = data.date_range
  const lines: string[] = [
    '# FabPulse engineer report',
    '',
    `Generated: ${data.generated_at}  `,
    `Window: ${bounds.min_date ?? 'first day'} → ${bounds.max_date ?? 'last day'}  `,
    `Tools: ${data.counts.tools ?? 0} · Events: ${(data.counts.events ?? 0).toLocaleString()} · Faults: ${(data.counts.fault_events ?? 0).toLocaleString()}`,
    '',
    '## Headline KPIs',
    '',
    '| Metric | Value | What it means |',
    '| --- | --- | --- |',
    ...data.headline.map(
      (item) => `| ${md(item.label)} | **${md(item.value)}** | ${md(item.detail)} |`,
    ),
    '',
    '## What the data says',
    '',
    ...data.summary_sentences.map((sentence) => `- ${sentence}`),
    '',
    '## Top ranked excursions',
    '',
    '| # | Tool | Metric | Severity | Finding |',
    '| --- | --- | --- | --- | --- |',
  ]
  if (data.excursions.length) {
    for (const item of data.excursions) {
      lines.push(
        `| ${item.rank} | ${md(item.tool_id)} | ${md(item.metric)} | ${md(item.severity)} | ${md(item.headline)} |`,
      )
    }
  } else {
    lines.push('| — | — | — | — | No excursions in this window. |')
  }

  lines.push(
    '',
    '## Pareto: fault codes behind 80% of events',
    '',
    '| Fault code | Category | Severity | Events | % of total | Cumulative % |',
    '| --- | --- | --- | ---: | ---: | ---: |',
  )
  for (const row of data.pareto_drivers) {
    lines.push(
      `| ${md(row.fault_code)} | ${md(row.fault_category)} | ${md(row.severity)} | ${row.count.toLocaleString()} | ${row.pct_of_total.toFixed(1)}% | ${row.cumulative_pct.toFixed(1)}% |`,
    )
  }

  lines.push(
    '',
    '## Most significant shift-over-shift deltas',
    '',
    '| Tool | Handoff | Δ | Δ % | Welch p | Significant |',
    '| --- | --- | ---: | ---: | --- | --- |',
  )
  for (const item of data.shift_deltas) {
    const pValue =
      item.p_value === null ? 'n/a' : item.p_value < 0.001 ? '< 0.001' : item.p_value.toFixed(3)
    lines.push(
      `| ${md(item.tool_id)} | ${item.from_shift} → ${item.to_shift} | ${item.abs_delta.toFixed(2)} | ${item.pct_delta === null ? 'n/a' : `${item.pct_delta.toFixed(1)}%`} | ${pValue} | ${item.significant ? 'yes' : 'no'} |`,
    )
  }

  lines.push('', '## Glossary', '')
  for (const entry of data.glossary) {
    lines.push(`- **${entry.term}** — ${entry.definition}`)
  }
  lines.push(
    '',
    '---',
    '',
    'Generated by FabPulse. Control limits use mean ± 3σ; Tukey fences use 1.5×IQR.',
    '',
  )
  return lines.join('\n')
}

/** Render a tidy CSV (section,item,detail,value) for spreadsheet consumers. */
export function reportToCsv(data: ReportResponse): string {
  const rows: Array<[string, string, string, string]> = []
  for (const item of data.headline) rows.push(['headline', item.label, item.detail, item.value])
  for (const sentence of data.summary_sentences) rows.push(['summary', 'finding', sentence, ''])
  for (const item of data.excursions) {
    rows.push([
      'excursion',
      `#${item.rank} ${item.tool_id} ${item.metric}`,
      item.headline,
      item.severity,
    ])
  }
  for (const row of data.pareto_drivers) {
    rows.push([
      'pareto',
      row.fault_code,
      `${row.fault_category} / ${row.severity}`,
      `${row.count} events (${row.pct_of_total.toFixed(1)}%, cumulative ${row.cumulative_pct.toFixed(1)}%)`,
    ])
  }
  for (const item of data.shift_deltas) {
    rows.push([
      'shift_delta',
      `${item.tool_id} ${item.from_shift}->${item.to_shift}`,
      item.p_value === null ? 'p=n/a' : `p=${item.p_value}`,
      item.pct_delta === null ? '' : `${item.pct_delta.toFixed(1)}%`,
    ])
  }
  for (const entry of data.glossary) rows.push(['glossary', entry.term, entry.definition, ''])
  return [['section', 'item', 'detail', 'value'], ...rows]
    .map((row) => row.map((cell) => escapeCsv(cell)).join(','))
    .join('\n')
}

/** Trigger a client-side file download without a server round trip. */
export function downloadText(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  document.body.appendChild(anchor)
  anchor.click()
  document.body.removeChild(anchor)
  URL.revokeObjectURL(url)
}
